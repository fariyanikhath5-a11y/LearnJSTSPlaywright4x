// Array destructuring is a JavaScript syntax introduced in ES6 that allows you to unpack values
//  from arrays into distinct variables in a single, highly readable line

let [a ,b,c] = [10,20,30];
console.log(a); //10
console.log(b); //20
console.log(c); //30

const fruits = ['Apple' , 'banana' , 'strawberry'];
// Destructuring assignment
const[first,second,third] = fruits;
console.log(first); //Apple
console.log(second); //banana
console.log(third); // strawberry



